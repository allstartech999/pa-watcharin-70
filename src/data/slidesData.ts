export interface VisualPhotoItem {
  title: string;
  badge: string;
  imageUrl: string;
  highlight?: string;
}

export interface RelatedLinkItem {
  targetSlideIndex: number;
  label: string;
  badge: string;
  relationType: 'contributes_to' | 'derived_from' | 'aligns_with';
  note: string;
}

export interface ChallengeDetailInfo {
  officialTitle: string;
  problemSummary: string;
  methods: { step: string; detail: string }[];
  outcomesQuantitative: string[];
  outcomesQualitative: string[];
}

export interface SlideItem {
  id: number;
  category: string;
  badge: string;
  title: string;
  tagline: string;
  section: 'home' | 'part1' | 'part2';
  theme: {
    bgGradient: string;
    accent: string;
    badgeColor: string;
  };
  layout: 'cover' | 'overview' | 'photo-mosaic' | 'safe-model' | 'vocational-showcase' | 'closing' | 'toc';
  director?: {
    name: string;
    position: string;
    academic: string;
    school: string;
    affiliation: string;
    avatarUrl: string;
    year: string;
    round: string;
  };
  vocational?: {
    grade: string;
    name: string;
    concept: string;
    tags: string[];
  };
  // ข้อความเดิมจากเว็บเดิมเป๊ะๆ สำหรับส่วนที่ 1
  originalContentText?: string[];
  // ข้อมูลทางการส่วนที่ 2 (สภาพปัญหา, วิธีการ PDCA, ผลลัพธ์ที่คาดหวัง)
  challengeInfo?: ChallengeDetailInfo;
  // ข้อมูลการเชื่อมโยงระหว่าง ส่วนที่ 1 และ ส่วนที่ 2
  relatedLinks?: RelatedLinkItem[];
  photos: VisualPhotoItem[];
}

